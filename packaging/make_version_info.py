"""Writes packaging/version_info.txt (the "Details" tab of JARVIS.exe) from app.__version__."""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from app import __app_name__, __version__  # noqa: E402

TEMPLATE = """# Generated by make_version_info.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={t}, prodvers={t}, mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0,
                    date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('FileDescription', '{name}'),
      StringStruct('FileVersion', '{v}'),
      StringStruct('InternalName', 'JARVIS'),
      StringStruct('OriginalFilename', 'JARVIS.exe'),
      StringStruct('ProductName', '{name}'),
      StringStruct('ProductVersion', '{v}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main() -> Path:
    parts = [int(p) for p in __version__.split(".")[:3]] + [0]
    out = HERE / "version_info.txt"
    out.write_text(TEMPLATE.format(t=tuple(parts[:4]), v=__version__, name=__app_name__), encoding="utf-8")
    return out


if __name__ == "__main__":
    print(main())
